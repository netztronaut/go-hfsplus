package main

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

// emit renders hfsplus/unicode_tables.go.
func emit(m *measured, t *tables, rep *report, license string) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	body, err := emitTables(t, rep)
	if err != nil {
		return nil, err
	}

	w("// Code generated by go run ./internal/gen/unicode; DO NOT EDIT.\n\n")
	w("// HFS+ name tables: Apple's decomposition, combining classes and case folding.\n//\n")
	w("// Produced from the Unicode 3.2 character database (UnicodeData-3.2.0.txt: canonical\n")
	w("// decompositions minus Apple's exclusions U+2000-U+2FFF, U+F900-U+FAFF, U+2F800-U+2FAFF;\n")
	w("// canonical combining classes; simple lowercase mappings), then verified against and,\n")
	w("// where they disagree, corrected by measurements of the macOS kernel's HFS+ code taken\n")
	w("// on %s on macOS %s, Darwin %s, %s:\n", m.meta["date"], m.meta["macos"], m.meta["darwin"], m.meta["hfs_kext"])
	w("// names created through POSIX on hdiutil images, what the kernel stored read back from\n")
	w("// the raw catalog B-tree (stored forms, collisions of O_EXCL creates, on-disk key order),\n")
	w("// and lookups against catalogs patched to hold units the kernel never writes itself\n")
	w("// (see measure_darwin.go and probe_darwin.go). The measurements are in\n")
	w("// internal/gen/unicode/testdata; the generator refuses to write this file unless the\n")
	w("// tables reproduce all of them. Findings:\n//\n")
	for _, l := range rep.lines {
		for _, s := range wrap(l, 92) {
			w("//\t%s\n", s)
		}
	}
	w("//\n// The derived Unicode data is used under the following notice:\n//\n")
	for _, l := range strings.Split(strings.TrimRight(license, "\n"), "\n") {
		if l == "" {
			w("//\n")
		} else {
			w("//\t%s\n", l)
		}
	}
	w("\npackage hfsplus\n\n")
	b.Write(body)
	return format.Source(b.Bytes())
}

func emitTables(t *tables, rep *report) ([]byte, error) {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	// Decompositions.
	keys := make([]uint16, 0, len(t.decomp))
	for k := range t.decomp {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var data []uint16
	start := []uint16{0}
	for _, k := range keys {
		data = append(data, t.decomp[k]...)
		start = append(start, uint16(len(data)))
	}
	w("// decompKeys lists, sorted, the BMP code points the kernel stores as something other than\n")
	w("// themselves, apart from Hangul syllables (algorithmic), ':', U+2400 and escapedRunes.\n")
	w("// The stored form of decompKeys[i] is decompData[decompStart[i]:decompStart[i+1]]: fully\n")
	w("// decomposed and canonically ordered.\n")
	w("var decompKeys = [%d]uint16{", len(keys))
	hexList(&b, keys, 12)
	w("}\n\nvar decompStart = [%d]uint16{", len(start))
	decList(&b, start, 16)
	w("}\n\nvar decompData = [%d]uint16{", len(data))
	hexList(&b, data, 12)
	w("}\n\n")

	w("// escapedRunes are the code points the kernel refuses as illegal and stores as the\n")
	w("// \"%%XX\" escapes of their UTF-8 bytes, sorted.\n")
	w("var escapedRunes = [%d]rune{", len(t.escaped))
	var er []uint16
	for _, r := range t.escaped {
		er = append(er, uint16(r))
	}
	hexList(&b, er, 12)
	w("}\n\n")

	// Combining classes.
	var cccIdx [256]uint8
	var cccPages []uint16
	for p := 0; p < 256; p++ {
		page := t.ccc[p<<8 : p<<8+256]
		if slices.ContainsFunc(page, func(c uint8) bool { return c != 0 }) {
			for _, c := range page {
				cccPages = append(cccPages, uint16(c))
			}
			cccIdx[p] = uint8(len(cccPages) / 256)
		}
	}
	w("// cccIndex maps the high byte of a unit to its 1-based page in cccPages, 0 if every unit\n")
	w("// of that page has combining class 0. The classes are the kernel's, numbered as Unicode 3.2.\n")
	w("var cccIndex = [256]uint8{")
	idx := make([]uint16, 256)
	for i, v := range cccIdx {
		idx[i] = uint16(v)
	}
	decList(&b, idx, 32)
	w("}\n\nvar cccPages = [%d]uint8{", len(cccPages))
	decList(&b, cccPages, 32)
	w("}\n\n")

	// Case folding.
	var foldIdx [256]uint8
	var foldPages []uint16
	for p := 0; p < 256; p++ {
		ident := true
		for i := 0; i < 256; i++ {
			if t.fold[p<<8|i] != uint16(p<<8|i) {
				ident = false
				break
			}
		}
		if !ident {
			foldPages = append(foldPages, t.fold[p<<8:p<<8+256]...)
			foldIdx[p] = uint8(len(foldPages) / 256)
		}
	}
	w("// foldIndex maps the high byte of a unit to its 1-based page in foldPages, 0 if every unit\n")
	w("// of that page folds to itself; foldPages holds the folded value of each unit of a page,\n")
	w("// 0 for units FastUnicodeCompare ignores.\n")
	w("var foldIndex = [256]uint8{")
	for i, v := range foldIdx {
		idx[i] = uint16(v)
	}
	decList(&b, idx, 32)
	w("}\n\nvar foldPages = [%d]uint16{", len(foldPages))
	hexList(&b, foldPages, 12)
	w("}\n")

	rep.addf("tables: %d decompositions (%d units of data), %d escaped runes, %d combining-class pages, %d fold pages; %d bytes",
		len(keys), len(data), len(t.escaped), len(cccPages)/256, len(foldPages)/256,
		2*len(keys)+2*len(start)+2*len(data)+4*len(t.escaped)+256+len(cccPages)+256+2*len(foldPages))
	return b.Bytes(), nil
}

func hexList(b *bytes.Buffer, v []uint16, per int) {
	for i, x := range v {
		if i%per == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteByte(' ')
		}
		fmt.Fprintf(b, "0x%04X,", x)
	}
	b.WriteString("\n")
}

func decList(b *bytes.Buffer, v []uint16, per int) {
	for i, x := range v {
		if i%per == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteByte(' ')
		}
		fmt.Fprintf(b, "%d,", x)
	}
	b.WriteString("\n")
}

func wrap(s string, n int) []string {
	var out []string
	for len(s) > n {
		i := strings.LastIndex(s[:n], " ")
		if i <= 0 {
			break
		}
		out = append(out, s[:i])
		s = "  " + strings.TrimLeft(s[i+1:], " ")
	}
	return append(out, s)
}
